# Loaded so the model tags against the real syllabus vocabulary rather than
# inventing unit names. Generated by scripts/dump-syllabus-units.ts.
def load_unit_vocabulary(semester: int | None = None) -> str:
    """Every generated semester vocabulary, not just one.

    This was pinned to semester 6, which silently produced untaggable papers
    the moment a semester-2 or semester-4 scan went through: the model had no
    valid unit_id to choose and correctly left `units` empty. The semester is
    not known until the header is read, so all available vocabularies go in
    and the prompt's subject-code prefix rule does the selection.
    """
    schema_dir = Path(__file__).parent.parent / "schema"
    if semester is not None:
        paths = [schema_dir / f"units.sem{semester}.json"]
    else:
        paths = sorted(schema_dir.glob("units.sem*.json"))

    lines = []
    for path in paths:
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        lines.append(f'--- Semester {data["semester"]} ---')
        for subj in data["subjects"]:
            lines.append(f'{subj["subject_code"]} — {subj["subject_name"]}:')
            for u in subj["units"]:
                lines.append(f'  {u["unit_id"]}: {u["title"]}')
    return "\n".join(lines)


