const path = require('path');

const sa = JSON.parse(fs.readFileSync(path.join(__dirname, '../serviceAccountKey.json'), 'utf8'));

// Convert actual newlines in private key to escaped \n for .env file
const pk = sa.private_key.replace(/\n/g, '\\n');

const envLines = [
  `FIREBASE_PROJECT_ID=${sa.project_id}`,
  `FIREBASE_CLIENT_EMAIL=${sa.client_email}`,
  `FIREBASE_PRIVATE_KEY="${pk}"`
];

console.log('--- Copy these lines into .env.local ---');
envLines.forEach(l => console.log(l));
